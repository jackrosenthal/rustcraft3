const HEAD: usize = 0;
const NONE: usize = usize::MAX;

#[derive(Clone, Copy)]
struct Item {
    next: usize,
    prev: usize,
    value: u32,
    weight: u32,
    parent: usize,
    child_lo: usize,
}

struct Tree {
    items: Vec<Item>,
    by_value: [usize; 0x102],
}

enum At {
    After,
    Before,
}

impl Tree {
    fn new(kind: u8) -> Result<Self, Error> {
        let weights = WEIGHTS
            .get(kind as usize)
            .ok_or(Error::Corrupt("huffman compression type"))?;
        let head = Item { next: HEAD, prev: HEAD, value: 0, weight: 0, parent: NONE, child_lo: NONE };
        let mut t = Tree { items: vec![head], by_value: [NONE; 0x102] };
        let mut max_weight = 0;
        for (v, &w) in weights.iter().enumerate() {
            if w == 0 {
                continue;
            }
            let w = w as u32;
            let it = t.create(v as u32, w, At::After, HEAD);
            t.by_value[v] = it;
            if w < max_weight {
                let p = t.find_higher_or_equal(t.items[HEAD].prev, w);
                t.insert(it, At::After, p);
            }
            max_weight = max_weight.max(w);
        }
        for v in [0x100, 0x101] {
            t.by_value[v] = t.create(v as u32, 1, At::Before, HEAD);
        }
        let mut lo = t.items[HEAD].prev;
        while lo != HEAD {
            let hi = t.items[lo].prev;
            if hi == HEAD {
                break;
            }
            let w = t.items[hi].weight + t.items[lo].weight;
            let n = t.create(0, w, At::After, HEAD);
            t.items[lo].parent = n;
            t.items[hi].parent = n;
            t.items[n].child_lo = lo;
            if w < max_weight {
                let p = t.find_higher_or_equal(t.items[hi].prev, w);
                t.insert(n, At::After, p);
            }
            max_weight = max_weight.max(w);
            lo = t.items[hi].prev;
        }
        Ok(t)
    }

    fn unlink(&mut self, i: usize) {
        let Item { next, prev, .. } = self.items[i];
        self.items[prev].next = next;
        self.items[next].prev = prev;
    }

    fn insert(&mut self, i: usize, at: At, point: usize) {
        self.unlink(i);
        let (prev, next) = match at {
            At::After => (point, self.items[point].next),
            At::Before => (self.items[point].prev, point),
        };
        self.items[i].prev = prev;
        self.items[i].next = next;
        self.items[prev].next = i;
        self.items[next].prev = i;
    }

    fn create(&mut self, value: u32, weight: u32, at: At, point: usize) -> usize {
        let i = self.items.len();
        self.items.push(Item { next: i, prev: i, value, weight, parent: NONE, child_lo: NONE });
        self.insert(i, at, point);
        i
    }

    /// Walks toward the front from `i` and returns the first item at least `weight` heavy,
    /// or the list head.
    fn find_higher_or_equal(&self, mut i: usize, weight: u32) -> usize {
        while i != HEAD {
            if self.items[i].weight >= weight {
                return i;
            }
            i = self.items[i].prev;
        }
        HEAD
    }

    fn inc_weights(&mut self, mut i: usize) {
        while i != NONE {
            self.items[i].weight += 1;
            let w = self.items[i].weight;
            let higher = self.find_higher_or_equal(self.items[i].prev, w);
            let hi = self.items[higher].next;
            if hi != i {
                self.insert(hi, At::Before, i);
                self.insert(i, At::After, higher);
                let (pi, ph) = (self.items[i].parent, self.items[hi].parent);
                let hi_was_lo = self.items[ph].child_lo == hi;
                if self.items[pi].child_lo == i {
                    self.items[pi].child_lo = hi;
                }
                if hi_was_lo {
                    self.items[ph].child_lo = i;
                }
                self.items[i].parent = ph;
                self.items[hi].parent = pi;
            }
            i = self.items[i].parent;
        }
    }

    fn insert_new_branch(&mut self, value: u32) {
        let last = self.items[HEAD].prev;
        let (lv, lw) = (self.items[last].value, self.items[last].weight);
        let hi = self.create(lv, lw, At::Before, HEAD);
        self.items[hi].parent = last;
        self.by_value[lv as usize] = hi;
        let lo = self.create(value, 0, At::Before, HEAD);
        self.items[lo].parent = last;
        self.items[last].child_lo = lo;
        self.by_value[value as usize] = lo;
        self.inc_weights(lo);
    }
}

struct Bits<'a> {
    data: &'a [u8],
    pos: usize,
}

impl Bits<'_> {
    fn bit(&mut self) -> Option<u32> {
        let b = *self.data.get(self.pos / 8)?;
        let r = (b >> (self.pos % 8)) & 1;
        self.pos += 1;
        Some(r as u32)
    }
    fn byte(&mut self) -> Option<u32> {
        let mut v = 0;
        for i in 0..8 {
            v |= self.bit()? << i;
        }
        Some(v)
    }
}

pub fn decompress(input: &[u8], out_len: usize) -> Result<Vec<u8>, Error> {
    let mut bits = Bits { data: input, pos: 0 };
    let kind = bits.byte().ok_or(Error::Corrupt("huffman header"))? as u8;
    let mut t = Tree::new(kind)?;
    let adaptive = kind == 0;
    let mut out = Vec::with_capacity(out_len);
    let eof = || Error::Corrupt("huffman stream truncated");
    while out.len() < out_len {
        let mut i = t.items[HEAD].next;
        while t.items[i].child_lo != NONE {
            let lo = t.items[i].child_lo;
            i = if bits.bit().ok_or_else(eof)? != 0 {
                t.items[lo].prev
            } else {
                lo
            };
        }
        let mut v = t.items[i].value;
        if v == 0x100 {
            break;
        }
        if v == 0x101 {
            v = bits.byte().ok_or_else(eof)?;
            t.insert_new_branch(v);
            if !adaptive {
                t.inc_weights(t.by_value[v as usize]);
            }
            out.push(v as u8);
            if adaptive {
                t.inc_weights(t.by_value[v as usize]);
            }
            continue;
        }
        out.push(v as u8);
        if adaptive {
            t.inc_weights(t.by_value[v as usize]);
        }
    }
    Ok(out)
}
