"""Layouts for the ability and buff classes no record of the original's has been read
for, settled from the decompile alone (xlate.py: own and save translated, timers by
the classes' constructors), written into the formats crate's table (between its
generated markers) and into crates/game/src/w3zsave/kind_layouts.rs for the writer
(each kind's own fields past the ability's thirteen, and its tail).

    python3 classmap.py <game4.c> <game_vtables.tsv> > classmap.txt
    W3_DECOMP=<game4.c> python3 genlayouts.py classmap.txt
"""
import os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, '..', '..')
sys.path.insert(0, HERE)
import xlate, codenames

W3Z = os.path.join(ROOT, 'crates', 'formats', 'src', 'w3z.rs')
OUT = os.path.join(ROOT, 'crates', 'game', 'src', 'w3zsave', 'kind_layouts.rs')
BEGIN = '    // BEGIN genlayouts.py'
END = '    // END genlayouts.py'
BASE = 'wwww wwwwwww t w'

names = codenames.names()
inv = {v: k for k, v in names.items()}
src = open(W3Z).read()
if BEGIN in src:
    src = src[:src.index(BEGIN)] + src[src.index(END) + len(END) + 1:]
have = set()
for m in re.finditer(r'\((codes::\w+::id::\w+|b"(.{4})"),', src):
    have.add(m.group(2) or inv.get(m.group(1)))
rows = [ln.split() for ln in open(sys.argv[1])]
out = []
for code, cls, sv, own, rd in rows:
    if code[0] not in 'AB' or code in have or code not in names:
        continue
    o = xlate.translate('FUN_' + own, 'own')
    t = xlate.translate('FUN_' + sv, 'save')
    if o is None or t is None:
        continue
    o, t = xlate.resolve(o, cls), xlate.resolve(t, cls)
    if 'T' in o or 'T' in t or not re.sub(r'\s', '', o).startswith(re.sub(r'\s', '', BASE)):
        continue
    out.append((code, cls, re.sub(r'\s+', ' ', o).strip(), re.sub(r'\s+', ' ', t).strip()))

lines = [BEGIN + ': the classes read from the decompile alone (tools/saves).']
for code, cls, o, t in out:
    lines.append(f'    ({names[code]}, "{o}", "{t}"), // {cls}')
lines.append(END)
anchor = '    // Abilities whose classes\' own fields and saves are those already read (their'
assert src.count(anchor) == 1
src = src.replace(anchor, '\n'.join(lines) + '\n' + anchor)
open(W3Z, 'w').write(src)

def own_extra(o):
    # The layout past the ability's own thirteen fields.
    toks = o.replace(' ', '')
    return toks[len(BASE.replace(' ', '')):]

rs = ['//! Generated by tools/saves/genlayouts.py: the ability and buff classes no record of',
      '//! the original\'s has been read for, their layouts settled from the decompile (each',
      '//! class\'s own fields and save translated, its timers by its constructors).  Each',
      '//! kind\'s own fields past the ability\'s thirteen, and its tail.', '',
      'use crate::codes;', '',
      'pub(super) fn kind_layout(code: &[u8; 4]) -> Option<(&\'static str, &\'static str)> {',
      '    Some(match code {']
for code, cls, o, t in out:
    rs.append(f'        {names[code]} => ("{own_extra(o)}", "{t}"),')
rs += ['        _ => return None,', '    })', '}', '']
open(OUT, 'w').write('\n'.join(rs))
print(len(out), 'kinds')
